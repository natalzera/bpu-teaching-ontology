#!/usr/bin/env python3
"""Generate a small human-readable HTML reference from ontology annotations."""
from html import escape
from pathlib import Path
from rdflib import Graph, RDF, RDFS, Namespace, OWL

ROOT = Path(__file__).resolve().parents[1]
ONT = ROOT / 'ontology.ttl'
OUT = ROOT / 'docs' / 'index.html'
SKOS = Namespace('http://www.w3.org/2004/02/skos/core#')
BPU = Namespace('https://example.org/bpu#')
g = Graph().parse(ONT, format='turtle')

def lit(subject, pred):
    values = list(g.objects(subject, pred))
    # Prefer English, then first available literal.
    values.sort(key=lambda x: (getattr(x, 'language', None) != 'en', str(x)))
    return str(values[0]) if values else ''

def local(uri):
    return str(uri).rsplit('#', 1)[-1].rsplit('/', 1)[-1]

def section(title, subjects):
    rows = []
    for s in sorted(subjects, key=str):
        label = lit(s, RDFS.label) or local(s)
        definition = lit(s, SKOS.definition) or ''
        rows.append(f'<tr><td><code>{escape(local(s))}</code><br>{escape(label)}</td><td>{escape(definition)}</td><td><a href="{escape(str(s), quote=True)}">IRI</a></td></tr>')
    return f'<h2>{escape(title)}</h2><table><thead><tr><th>Term</th><th>Definition</th><th>Identifier</th></tr></thead><tbody>{"".join(rows)}</tbody></table>'

classes = [s for s in g.subjects(RDF.type, OWL.Class) if str(s).startswith(str(BPU))]
objprops = [s for s in g.subjects(RDF.type, OWL.ObjectProperty) if str(s).startswith(str(BPU))]
datprops = [s for s in g.subjects(RDF.type, OWL.DatatypeProperty) if str(s).startswith(str(BPU))]
iri = 'https://example.org/bpu'
version = 'https://example.org/bpu/0.1.0'
html = f'''<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>BPU-Teaching ontology documentation</title><style>body{{font:16px/1.55 system-ui,sans-serif;max-width:1100px;margin:2rem auto;padding:0 1rem;color:#222}}table{{border-collapse:collapse;width:100%;margin:1rem 0 2rem}}th,td{{text-align:left;vertical-align:top;border:1px solid #ccc;padding:.55rem}}th{{background:#f2f2f2}}code{{overflow-wrap:anywhere}}.warning{{border-left:4px solid #b7791f;padding:.5rem 1rem;background:#fffaf0}}</style></head><body><h1>BPU-Teaching</h1><p>Brazilian Public University Teaching Ontology — generated from the annotations in <code>ontology.ttl</code>.</p><p><strong>Ontology IRI:</strong> <code>{iri}</code><br><strong>Version IRI:</strong> <code>{version}</code></p><p class="warning">Release note: these example.org identifiers are placeholders and should be replaced with stable identifiers controlled by the project owner.</p>{section('Local classes', classes)}{section('Object properties', objprops)}{section('Datatype properties', datprops)}<h2>Generation</h2><p>Generated by <code>scripts/generate_docs.py</code> using rdflib. This is a lightweight annotation-derived reference, not WIDOCO output.</p></body></html>'''
OUT.parent.mkdir(exist_ok=True)
OUT.write_text(html, encoding='utf-8')
print(f'Wrote {OUT.relative_to(ROOT)} ({len(classes)} classes, {len(objprops)} object properties, {len(datprops)} datatype properties)')
